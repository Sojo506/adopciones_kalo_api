        FROM FIDE_PRODUCTO_TB P
        LEFT JOIN (
            SELECT  ID_PRODUCTO,
                    SUM(CANTIDAD) AS CANTIDAD
            FROM FIDE_INVENTARIO_TB
            WHERE ID_ESTADO = 1
            GROUP BY ID_PRODUCTO
        ) I ON P.ID_PRODUCTO = I.ID_PRODUCTO
        WHERE P.ID_PRODUCTO = P_ID_PRODUCTO;

    RETURN V_CURSOR_RESULTADO;
