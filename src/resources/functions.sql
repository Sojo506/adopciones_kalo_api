        JOIN FIDE_PROVINCIA_TB PRO ON CAN.ID_PROVINCIA = PRO.ID_PROVINCIA
        JOIN FIDE_PAIS_TB PA ON PRO.ID_PAIS = PA.ID_PAIS
        JOIN FIDE_ESTADO_TB E ON CC.ID_ESTADO = E.ID_ESTADO
