FOR INSERT OR UPDATE OF ID_VENTA, ID_FACTURA, ID_ESTADO ON FIDE_VENTA_FACTURA_TB
COMPOUND TRIGGER
    TYPE T_FACTURA_IDS IS TABLE OF FIDE_FACTURA_TB.ID_FACTURA%TYPE INDEX BY PLS_INTEGER;
    G_FACTURA_IDS T_FACTURA_IDS;
    G_FACTURA_COUNT PLS_INTEGER := 0;

    PROCEDURE ADD_FACTURA_ID(P_ID_FACTURA IN FIDE_FACTURA_TB.ID_FACTURA%TYPE)
    IS
    BEGIN
        IF P_ID_FACTURA IS NULL THEN
            RETURN;
        END IF;

        FOR I IN 1 .. G_FACTURA_COUNT LOOP
            IF G_FACTURA_IDS(I) = P_ID_FACTURA THEN
                RETURN;
            END IF;
        END LOOP;

        G_FACTURA_COUNT := G_FACTURA_COUNT + 1;
        G_FACTURA_IDS(G_FACTURA_COUNT) := P_ID_FACTURA;
    END ADD_FACTURA_ID;

    AFTER EACH ROW
    IS
    BEGIN
        ADD_FACTURA_ID(:NEW.ID_FACTURA);

        IF UPDATING('ID_FACTURA') AND :OLD.ID_FACTURA <> :NEW.ID_FACTURA THEN
            ADD_FACTURA_ID(:OLD.ID_FACTURA);
        END IF;
    END AFTER EACH ROW;

    AFTER STATEMENT
    IS
    BEGIN
        FOR I IN 1 .. G_FACTURA_COUNT LOOP
            FIDE_KALO_PKG.FIDE_RECALCULAR_FACTURA_POR_ID_SP(G_FACTURA_IDS(I));
        END LOOP;
    END AFTER STATEMENT;
END FIDE_VENTA_FACTURA_CALC_TRG;
