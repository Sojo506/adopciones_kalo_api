CREATE OR REPLACE FUNCTION FIDE_ALPHA_NUMERIC_SEQ_FN
RETURN VARCHAR2 AS
    V_FECHA VARCHAR2(10);
    V_LETRA CHAR(1);
    V_VALOR VARCHAR2(30);
BEGIN
    V_FECHA := TO_CHAR(SYSDATE, 'DDMMYYY');
    V_LETRA := CHR(65 + TRUNC(DBMS_RANDOM.VALUE(0, 26)));
    V_VALOR := V_FECHA || '-' || LPAD(FIDE_FACTURA_SEQ.NEXTVAL, 7, '0') || '-' || V_LETRA;

    RETURN V_VALOR;
END FIDE_ALPHA_NUMERIC_SEQ_FN;
/

CREATE OR REPLACE TRIGGER FIDE_ESTADO_INSERT_TRG
BEFORE INSERT ON FIDE_ESTADO_TB
FOR EACH ROW
BEGIN
    IF :NEW.ID_ESTADO IS NULL THEN
        :NEW.ID_ESTADO := FIDE_ESTADO_SEQ.NEXTVAL;
    END IF;
    :NEW.FECHA_CREACION := SYSTIMESTAMP;
    :NEW.CREADO_POR := SYS_CONTEXT('USERENV', 'SESSION_USER');
    :NEW.ACCION := 'INSERT';
END FIDE_ESTADO_INSERT_TRG;
/

CREATE OR REPLACE TRIGGER FIDE_ESTADO_UPDATE_TRG
BEFORE UPDATE ON FIDE_ESTADO_TB
FOR EACH ROW
BEGIN
    IF NOT (NVL(:NEW.ID_ESTADO, -1) = 2 AND NVL(:OLD.ID_ESTADO, -1) <> 2) THEN
        :NEW.FECHA_MODIFICACION := SYSTIMESTAMP;
        :NEW.MODIFICADO_POR := SYS_CONTEXT('USERENV', 'SESSION_USER');
        :NEW.ACCION := 'UPDATE';
    END IF;
END FIDE_ESTADO_UPDATE_TRG;
/

